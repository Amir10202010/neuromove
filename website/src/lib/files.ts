// Чтение файлов, которые выбрал пользователь. Файл — чужие данные: сначала размер, потом чтение.
// Гигабайтный файл, прочитанный целиком, повесит вкладку посреди приёма.

/** Запись сеанса: 5 датчиков × 100 Гц текстом — около 20 КБ в секунду, 15 минут — около 20 МБ. */
export const MAX_RECORDING_MB = 64;
/** Архив пространства: сотни сеансов без сырых данных — единицы мегабайт. */
export const MAX_BACKUP_MB = 50;

/** Текст файла или null, если файл больше предела. */
export async function readTextFile(file: File, maxMb: number): Promise<string | null> {
  if (file.size > maxMb * 1024 * 1024) return null;
  return file.text();
}
