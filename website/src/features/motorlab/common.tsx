export function useNames() {
  const { t } = useI18n();
  return {
    exercise: (e: ExerciseId) => t(`exercise.${e}.name` as never),
    side: (s: Side) => t(`side.${s}` as never),
    task: (e: ExerciseId, s: Side) => `${t(`exercise.${e}.name` as never)} · ${t(`side.${s}` as never)}`,
  };
}

/** Dates in the interface language (the stored value stays ISO). */
export function useDates() {
  const locale = useAppStore((s) => s.settings.locale);
  const tag = locale === 'en' ? 'en-GB' : locale === 'kk' ? 'kk-KZ' : 'ru-RU';
  return { date: (iso: string) => new Date(iso).toLocaleDateString(tag), dateTime: (iso: string) => new Date(iso).toLocaleString(tag, { dateStyle: 'medium', timeStyle: 'short' }) };
}

/** Display formatting only; stored values are never rounded. */
export function fmt(v: number | null | undefined, digits = 1): string {
  if (v === null || v === undefined || !Number.isFinite(v)) return '—';
  return v.toFixed(digits).replace('-', '−');
}

export function digitsFor(unit: string): number {
  return unit === 's' ? 2 : unit === '' ? 2 : 1;
}

export function withUnit(v: number | null | undefined, unit: string, digits = digitsFor(unit)): string {
  const s = fmt(v, digits);
  return s === '—' || !unit ? s : unit === '°' ? `${s}°` : `${s} ${unit}`;
}

/** Profile interval "[lo; hi]" with open sides marked. */
export function Interval({ lo, hi, loOpen, hiOpen, digits }: { lo: number; hi: number; loOpen: boolean; hiOpen: boolean; digits: number }) {
  const lt = useLT();
  return (
    <span className="mlinterval">
      [{loOpen ? <span className="mlopen" title={lt('not bounded by the data')}>{lt('open')}</span> : fmt(lo, digits)}; {hiOpen ? <span className="mlopen" title={lt('not bounded by the data')}>{lt('open')}</span> : fmt(hi, digits)}]
    </span>
  );
}
