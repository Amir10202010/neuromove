/** Workspace data + practice records + lab records, loaded once. Demo workspace = simulated data, labelled. */
export function useLabData() {
  const { ws, patients, sessions } = useWorkspaceData();
  const rehabLoaded = useRehabStore((s) => s.loaded);
  const loadRehab = useRehabStore((s) => s.load);
  const records = useRehabStore((s) => s.records);
  const labLoaded = useLabStore((s) => s.loaded);
  const loadLab = useLabStore((s) => s.load);
  useEffect(() => {
    if (!rehabLoaded) void loadRehab();
    if (!labLoaded) void loadLab();
  }, [rehabLoaded, loadRehab, labLoaded, loadLab]);
  const practice = useMemo(() => records.filter((r): r is PracticeRecord => r.kind === 'practice' && r.workspace === ws), [records, ws]);
  // Симулированные сеансы участвуют везде — и в демо, и в клинике; баннер «синтетические данные» показывается, если они есть
  const includeSimulated = true;
  return { ws, patients, sessions, practice, includeSimulated, ready: rehabLoaded && labLoaded };
}

export function useParticipantSeries(participantId: string | null) {
  const d = useLabData();
  const series = useMemo(
    () => (participantId ? buildParticipantSeries(participantId, d.sessions, { includeSimulated: d.includeSimulated, practice: d.practice }) : []),
    [participantId, d.sessions, d.includeSimulated, d.practice],
  );
  return { ...d, series };
}

export function Prov({ kind }: { kind: Provenance }) {
  const lt = useLT();
  const label: Record<Provenance, LKey> = { measured: 'measured', derived: 'calculated from IMU', estimated: 'model estimate', predicted: 'prediction', hypothetical: 'hypothetical' };
  return <span className={`mlprov mlprov--${kind}`}>{lt(label[kind])}</span>;
}

export function SimulatedBanner({ show }: { show: boolean }) {
  const lt = useLT();
  const { ws, sessions } = useWorkspaceData();
  const present = ws === 'demo' || sessions.some((s) => s.demo || s.device.simulated || s.device.kind === 'simulator');
  if (!show || !present) return null;
  return (
    <div className="callout callout--demo" role="note">
      <FlaskConical aria-hidden />
      <div>
        <div className="callout__title">{lt('Synthetic demonstration data')}</div>
        {lt('These sessions were generated by the virtual-patient simulator. Every number on this page is computed by the real analysis engine, but it describes simulated children, not real ones.')}
      </div>
    </div>
  );
}

