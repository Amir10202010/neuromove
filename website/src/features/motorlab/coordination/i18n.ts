/** Unknown keys (engine reason codes, numbers) are shown as they are. */
export function useCT(): CT {
  const locale = useAppStore((s) => s.settings.locale);
  return useMemo<CT>(() => (key) => (locale === 'en' ? key : ((locale === 'kk' ? (KK as Record<string, string>)[key] : (RU as Record<string, string>)[key]) ?? key)), [locale]);
}

