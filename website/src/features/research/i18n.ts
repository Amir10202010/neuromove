export type RKey = keyof typeof RU;
export type RT = (key: RKey, params?: Record<string, string | number>) => string;

function interpolate(s: string, params?: Record<string, string | number>): string {
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : s;
}

export function useRT(): RT {
  const locale = useAppStore((s) => s.settings.locale);
  return useMemo<RT>(() => (key, params) => interpolate(locale === 'en' ? key : RU[key], params), [locale]);
}

/** Display formatting only — stored values are never rounded. */
export function fmtNum(v: number | null | undefined, digits: number, signed = false): string {
  if (v === null || v === undefined || !Number.isFinite(v)) return '—';
  const s = v.toFixed(digits);
  return signed && v > 0 ? `+${s}` : s.replace('-', '−');
}

export function fmtDeg(v: number | null | undefined, digits: number, signed = false): string {
  const s = fmtNum(v, digits, signed);
  return s === '—' ? s : `${s}°`;
}
