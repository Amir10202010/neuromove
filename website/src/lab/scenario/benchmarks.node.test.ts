// Consolidated runner of the research-frontier benchmark registry (measurement, strategy, observatory, twin,
// scenarios G01–G20, statistical safeguards).
//   npm test            quick mode: the scenarios and the statistical safeguards with few replicates — each executes
//                       and returns finite values (the four component suites run quick in their own node tests:
//                       measure/, coord/strategy, observatory/, twin/ — not repeated here)
//   FRONTIER_FULL=1     full mode: every suite. FRONTIER_OUT=<file> writes all records as JSON;
//                       FRONTIER_LATEST=1 also rewrites src/lab/scenario/latest.ts (the summary the app shows).
// In full mode every criterion must pass EXCEPT the documented failures, which must still fail (so that a change
// is noticed and research/SCIENTIFIC_VALIDATION.md is updated). FRONTIER_NOASSERT=1 skips the assertions.
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { DOCUMENTED_FAILURES, collectBenchmarks, discoveryBenchmarks, scenarioBenchmarks, summarise } from './benchmarks';

const FULL = process.env.FRONTIER_FULL === '1';

const HEADER = [
  '// GENERATED by src/lab/scenario/benchmarks.node.test.ts (FRONTIER_FULL=1 FRONTIER_LATEST=1) — do not edit.',
  '// Results of the last FULL run of the research-frontier benchmark registry. SYNTHETIC data only: they show how',
  '// the software behaves under stated assumptions, not anything about real participants.',
  "import type { BenchmarkSummary } from './benchmarks';",
  '',
].join('\n');

describe('research-frontier benchmark registry', () => {
  it(
    FULL ? 'full suite' : 'quick suite',
    () => {
      const started = new Date().toISOString();
      const records = FULL ? collectBenchmarks(true) : [...scenarioBenchmarks(false), ...discoveryBenchmarks(false)];
      const summary = summarise(records, started);
      const out = process.env.FRONTIER_OUT;
      if (out) writeFileSync(out, JSON.stringify({ started, finished: new Date().toISOString(), node: process.version, ...summary }, null, 1));
      if (FULL && process.env.FRONTIER_LATEST === '1') writeFileSync(new URL('./latest.ts', import.meta.url), `${HEADER}\nexport const LATEST_BENCHMARKS: BenchmarkSummary | null = ${JSON.stringify(summary, null, 1)};\n`);
      expect(new Set(records.map((r) => r.id)).size, 'benchmark ids are unique').toBe(records.length);
      for (const r of records) if (r.value !== null) expect(Number.isFinite(r.value), `${r.id} value`).toBe(true);
      if (FULL && process.env.FRONTIER_NOASSERT !== '1') {
        for (const r of records) {
          if (r.pass === null) continue;
          if (DOCUMENTED_FAILURES.includes(r.id)) expect(r.pass, `${r.id} is a documented failure that no longer fails — update research/SCIENTIFIC_VALIDATION.md`).toBe(false);
          else expect(r.pass, `${r.id}: ${r.criterion} (value ${r.value}, ${JSON.stringify(r.detail)})`).toBe(true);
        }
      }
    },
    FULL ? 7_200_000 : 900_000,
  );
});
