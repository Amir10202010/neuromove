// Practice-trial capture and the trial-level learning models on synthetic ground truth.

import { describe, expect, it } from 'vitest';
import { createRng } from '../lib/random';
import { createMemoryStorage } from '../data/db';
import type { ConsentRecord } from '../rehab/model';
import type { EngineResult } from '../session/types';
import { fitTargetedPractice, MIN_PRACTICE_TRIALS, type TargetedTrial } from './dualRate';
import { labRecordProblem } from './integrity';
import { storeTrialSet, trialSetFromEngine } from './practice';
import { trialRecordingStatus, type LabRecord, type TrialRecordingSetting } from './records';

/** Targeted practice generated by a known process (z = c + x_f + x_s), with measurement noise. */
function practice(o: { n: number; target: number; c: number; Af?: number; As?: number; Bf?: number; Bs?: number; A?: number; B?: number; noise: number; seed: number; model: 'dual' | 'single' | 'none' }): TargetedTrial[] {
  const rng = createRng(o.seed);
  let xf = 0;
  let xs = 0;
  const out: TargetedTrial[] = [];
  for (let i = 0; i < o.n; i++) {
    const z = o.c + xf + xs;
    out.push({ target: o.target, y: z + rng.normal(0, o.noise) });
    const e = o.target - z;
    if (o.model === 'dual') {
      xf = (o.Af as number) * xf + (o.Bf as number) * e;
      xs = (o.As as number) * xs + (o.Bs as number) * e;
    } else if (o.model === 'single') xs = (o.A as number) * xs + (o.B as number) * e;
  }
  return out;
}

const engineResult = (roms: number[], flags: string[] = [], percent = 99): EngineResult =>
  ({
    steps: [{ summary: { reps: roms.map((rom, i) => ({ index: i, tStart: 4 * i, tEnd: 4 * i + 3, rom })), flags }, trace: { t: [], angle: [], trunk: [] }, status: 'done' }],
    events: [],
    quality: { received: 1000, lost: 0, saturated: 0, percent },
    activeSec: 60,
    totalSec: 60,
    calibrationAttempts: 1,
    calibrationPose: {},
    completed: true,
  }) as unknown as EngineResult;

describe('practice-trial capture', () => {
  const base = { workspace: 'clinic' as const, participantId: 'p1', exercise: 'shoulder_flexion' as const, side: 'right' as const, targetDeg: 120, startedAt: new Date('2026-11-08T10:00:00Z'), endedAt: new Date('2026-11-08T10:05:00Z'), consentId: 'c1', simulated: false };

  it('one trial per detected repetition, error = target − peak, sealed with a content hash', () => {
    const set = trialSetFromEngine({ ...base, result: engineResult([100, 104, 110]) })!;
    expect(set.trials.map((t) => [t.index, t.peakDeg, t.errorDeg, t.valid])).toEqual([[1, 100, 20, true], [2, 104, 16, true], [3, 110, 10, true]]);
    expect(labRecordProblem(set)).toBeNull();
    expect(labRecordProblem({ ...set, trials: set.trials.map((t) => ({ ...t, peakDeg: t.peakDeg + 1 })) })).toBe('bad_shape');
  });

  it('a sitting with a blocking flag or poor signal keeps its trials but marks them invalid', () => {
    expect(trialSetFromEngine({ ...base, result: engineResult([100], ['data_gap']) })!.trials[0]!.valid).toBe(false);
    expect(trialSetFromEngine({ ...base, result: engineResult([100], [], 80) })!.trials[0]!.valid).toBe(false);
    expect(trialSetFromEngine({ ...base, result: engineResult([]) })).toBeNull();
  });

  it('storage: clinic writes carry an outbox op in the same transaction; simulated clinic data are refused', async () => {
    const st = createMemoryStorage();
    const set = trialSetFromEngine({ ...base, result: engineResult([100, 101]) })!;
    expect(await storeTrialSet(st, set)).toBe(true);
    expect((await st.listOutbox()).map((o) => o.entity)).toEqual(['lab_record']);
    expect(await storeTrialSet(st, trialSetFromEngine({ ...base, simulated: true, result: engineResult([100]) })!)).toBe(false);
    const demo = trialSetFromEngine({ ...base, workspace: 'demo', simulated: true, consentId: null, result: engineResult([100]) })!;
    expect(await storeTrialSet(st, demo)).toBe(true);
    expect((await st.listOutbox()).length).toBe(1);
  });

  it('recording requires the newest setting enabled AND an active consent (clinic)', () => {
    const on: TrialRecordingSetting = { id: 't1', kind: 'trial_recording', workspace: 'clinic', participantId: 'p1', enabled: true, consentId: 'c1', createdAt: '2026-11-01T00:00:00Z', createdBy: 'Dr' };
    const off: TrialRecordingSetting = { ...on, id: 't2', enabled: false, consentId: null, createdAt: '2026-11-05T00:00:00Z' };
    const consent = { id: 'c1', kind: 'consent', workspace: 'clinic', participantId: 'p1', status: 'active' } as unknown as ConsentRecord;
    const withdrawn = { ...consent, status: 'withdrawn' } as ConsentRecord;
    expect(trialRecordingStatus('p1', 'clinic', [], [consent]).reason).toBe('not_enabled');
    expect(trialRecordingStatus('p1', 'clinic', [on] as LabRecord[], [consent]).enabled).toBe(true);
    expect(trialRecordingStatus('p1', 'clinic', [on] as LabRecord[], [withdrawn])).toMatchObject({ enabled: false, reason: 'no_active_consent' });
    expect(trialRecordingStatus('p1', 'clinic', [on, off] as LabRecord[], [consent]).enabled).toBe(false);
    expect(trialRecordingStatus('p1', 'demo', [{ ...on, workspace: 'demo' }] as LabRecord[], []).enabled).toBe(true);
  });
});

describe('targeted-practice models (synthetic ground truth)', () => {
  it('no learning in the data → "no learning" is selected', () => {
    const r = fitTargetedPractice(practice({ n: 80, target: 130, c: 100, noise: 3, seed: 1, model: 'none' }), { profiles: false })!;
    expect(r.selected).toBe('no_learning');
  });

  it('single-rate learning toward the target is detected and its rates recovered', () => {
    const r = fitTargetedPractice(practice({ n: 120, target: 130, c: 100, A: 0.98, B: 0.08, noise: 2, seed: 2, model: 'single' }))!;
    expect(r.selected).not.toBe('no_learning');
    const single = r.fits.find((f) => f.model === 'single_rate')!;
    expect(single.params.B).toBeGreaterThan(0.04);
    expect(single.params.B).toBeLessThan(0.16);
    expect(single.params.c).toBeGreaterThan(96);
    expect(single.params.c).toBeLessThan(104);
  });

  it('fewer than the minimum valid trials → only "no learning" is fitted, and it says so', () => {
    const r = fitTargetedPractice(practice({ n: MIN_PRACTICE_TRIALS - 5, target: 130, c: 100, A: 0.98, B: 0.1, noise: 2, seed: 3, model: 'single' }))!;
    expect(r.fits.map((f) => f.model)).toEqual(['no_learning']);
    expect(r.notes).toContain('too_few_trials');
  });

  it('invalid trials advance the dynamics but are not observed', () => {
    const t = practice({ n: 60, target: 130, c: 100, A: 0.98, B: 0.08, noise: 2, seed: 4, model: 'single' }).map((x, i) => (i % 5 === 0 ? { ...x, y: null } : x));
    const r = fitTargetedPractice(t, { profiles: false })!;
    expect(r.observed).toBe(48);
    expect(r.predicted.length).toBe(60);
  });
});
