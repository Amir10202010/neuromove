// Bundles server/entry.ts (+ the shared src/ modules it uses) into api/index.js — the single Vercel
// Function. Why a committed bundle instead of letting Vercel compile api/*.ts: this package is
// "type": "module" and the shared code uses extension-less imports, which Node's ESM loader cannot
// resolve at runtime. `postgres` stays external (installed from package.json, traced by Vercel).
//
//   npm run build:api          write api/index.js
//   npm run build:api -- --check   exit 1 if api/index.js is out of date (also a unit test)

import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'api/index.js');

export async function bundleApi() {
  const r = await build({
    entryPoints: [resolve(root, 'server/entry.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    external: ['postgres'],
    write: false,
    legalComments: 'none',
    banner: { js: '// GENERATED by scripts/build-api.mjs from server/*.ts and src/ — do not edit. Rebuild: npm run build:api' },
    define: { __APP_VERSION__: JSON.stringify(JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).version), __BUILD_DATE__: '"server"' },
    logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundleApi();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      /* missing */
    }
    if (current !== text) {
      console.error('api/index.js is out of date — run: npm run build:api');
      process.exit(1);
    }
    console.log('api/index.js is up to date');
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.log(`wrote ${out} (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
